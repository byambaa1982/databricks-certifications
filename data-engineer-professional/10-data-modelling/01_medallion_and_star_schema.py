# MAGIC ## Medallion: a contract per layer, not just three names
# MAGIC
# MAGIC | Layer | Contract | This repo's example |
# MAGIC |---|---|---|
# MAGIC | **Bronze** | raw, append-only, as-received (+ ingestion metadata); re-processable source of truth | `bronze_orders` — bad timestamps and all, `_source_file` kept |
# MAGIC | **Silver** | validated, deduplicated, conformed types, joinable entities | `silver_orders`, `silver_customers` (SCD2) |
# MAGIC | **Gold** | aggregated / modelled **for consumption** (BI marts, features) | `gold_daily_revenue`, `gold_customer_revenue` |
# MAGIC
# MAGIC > **Exam traps:**
# MAGIC > - Bronze keeps **bad records too** (drop them at silver) — bronze is what
# MAGIC >   lets you replay when the cleansing rules change.
# MAGIC > - Cleansing lives **bronze → silver**; business aggregation lives
# MAGIC >   **silver → gold**. Questions love putting the right step in the wrong
# MAGIC >   hop.
# MAGIC > - Layers are **schemas/naming conventions**, not a product feature — the
# MAGIC >   enforcement is your pipelines (sections 02–03).


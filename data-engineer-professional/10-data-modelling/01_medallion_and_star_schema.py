# MAGIC %md
# MAGIC ## Why stars work fine on the lakehouse (and when not to bother)
# MAGIC - Dimensions are small → they **broadcast** (section 06): a star join costs
# MAGIC   barely more than a scan of the fact.
# MAGIC - PK/FK are **informational** (section 03) but declare them anyway: BI
# MAGIC   tools, humans, and (with `RELY`) the optimizer use them.
# MAGIC - **Denormalize when** the join is hot, the attribute is stable, and
# MAGIC   consumers are non-SQL (one wide gold table beats teaching every consumer
# MAGIC   the joins). Storage is cheap; correctness of *slowly changing* attributes
# MAGIC   is the real cost of copying them into facts — which is why SCD (notebook
# MAGIC   02) is the flip side of this decision.
# MAGIC - Data Vault appears in one question flavor: hubs/links/satellites as the
# MAGIC   heavy-integration middle layer — know it's an *alternative silver
# MAGIC   modelling style*, feeding the same gold stars.


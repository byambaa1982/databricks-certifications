# MAGIC %md
# MAGIC ## The star: facts reference dimensions by surrogate key
# MAGIC Surrogate keys decouple your model from source-system ids (which get
# MAGIC recycled, collide across sources, and leak PII). On Databricks the tool is
# MAGIC an **identity column**:

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE OR REPLACE TABLE dim_customer_star (
# MAGIC   customer_sk BIGINT GENERATED ALWAYS AS IDENTITY,
# MAGIC   customer_id BIGINT,          -- the natural/business key
# MAGIC   name        STRING,
# MAGIC   tier        STRING
# MAGIC );
# MAGIC
# MAGIC INSERT INTO dim_customer_star (customer_id, name, tier)
# MAGIC SELECT customer_id, name, tier
# MAGIC FROM silver_customers WHERE __END_AT IS NULL;
# MAGIC
# MAGIC SELECT * FROM dim_customer_star ORDER BY customer_sk LIMIT 5

# COMMAND ----------

# MAGIC %md
# MAGIC > **Exam traps:**
# MAGIC > - `GENERATED ALWAYS AS IDENTITY` refuses explicit inserts into the column;
# MAGIC >   `GENERATED BY DEFAULT` allows them (needed for migrations/backfills).
# MAGIC > - Identity values are unique but **not necessarily consecutive** — gaps
# MAGIC >   are normal (retries, concurrency). Any answer requiring gap-free
# MAGIC >   sequences is wrong.
# MAGIC > - Identity columns make concurrent writes to the table conflict-prone —
# MAGIC >   they serialize inserts; for massively concurrent writers consider hashes
# MAGIC >   or UUIDs instead.

